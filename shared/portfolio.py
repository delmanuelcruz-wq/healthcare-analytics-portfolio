"""Helpers shared by every project: warehouse access, CSV output, dashboards, screenshots."""
import csv
import json
import shutil
import sqlite3
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOUNDATION = ROOT / "foundation"
WAREHOUSE = FOUNDATION / "warehouse.sqlite"
SHARED = ROOT / "shared"
PLOTLY_CDN = "https://cdn.jsdelivr.net/npm/plotly.js-dist-min@2.35.2/plotly.min.js"
DISCLAIMER = "SYNTHETIC DEMONSTRATION - not operational, medical or financial guidance"


def connect():
    """Open the warehouse, building it from the CSVs if needed."""
    if not WAREHOUSE.exists():
        sys.path.insert(0, str(FOUNDATION))
        import build_warehouse
        build_warehouse.build()
    con = sqlite3.connect(WAREHOUSE)
    con.row_factory = sqlite3.Row
    return con


def meta(con):
    return {r["key"]: r["value"] for r in con.execute("SELECT key, value FROM meta")}


def run_script(con, path: Path):
    con.executescript(path.read_text(encoding="utf-8"))


def query(con, sql_or_path, params=()):
    sql = sql_or_path.read_text(encoding="utf-8") if isinstance(sql_or_path, Path) else sql_or_path
    return [dict(r) for r in con.execute(sql, params)]


def scalar(con, sql, params=()):
    return con.execute(sql, params).fetchone()[0]


def write_csv(rows, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        if not rows:
            fh.write("")
            return
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def render_dashboard(template: Path, out: Path, data: dict, replacements: dict | None = None):
    """Inline shared CSS/JS and the data payload into a self-contained HTML page."""
    html = template.read_text(encoding="utf-8")
    html = html.replace("/*__SHARED_CSS__*/", (SHARED / "dashboard.css").read_text(encoding="utf-8"))
    html = html.replace("/*__SHARED_JS__*/", (SHARED / "dashboard.js").read_text(encoding="utf-8"))
    html = html.replace("__PLOTLY_CDN__", PLOTLY_CDN)
    html = html.replace("/*__DATA__*/", "window.DATA = " + json.dumps(data, default=str) + ";")
    for key, value in (replacements or {}).items():
        html = html.replace(key, str(value))
    out.write_text(html, encoding="utf-8")
    return out


def find_browser():
    for candidate in [r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
                      r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
                      r"C:\Program Files\Google\Chrome\Application\chrome.exe",
                      shutil.which("msedge"), shutil.which("google-chrome"), shutil.which("chromium")]:
        if candidate and Path(candidate).exists():
            return candidate
    return None


def screenshot(html: Path, png: Path, width=1440, height=2400, theme="light"):
    """Headless Edge/Chrome screenshot. Returns False (and skips) when no browser is installed."""
    browser = find_browser()
    if not browser:
        print("  (no Chromium browser found - skipping screenshot)")
        return False
    args = [browser, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
            f"--window-size={width},{height}", "--virtual-time-budget=15000", f"--screenshot={png}"]
    args.append(html.resolve().as_uri() + f"?theme={theme}")
    subprocess.run(args, check=True, capture_output=True, timeout=120)
    return png.exists()


