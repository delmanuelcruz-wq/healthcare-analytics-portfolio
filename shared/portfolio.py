def qa_summary(qa):
    n = {k: sum(c["status"] == k for c in qa) for k in ("pass", "warn", "fail")}
    return f"{n['pass']} pass / {n['warn']} warn / {n['fail']} fail"


def write_qa_log(path: Path, title: str, qa, snapshot="2026-10-24"):
    """Markdown QA log in the same format as projects A-D."""
    icon = {"pass": "PASS", "warn": "WARN", "fail": "FAIL"}
    lines = [f"# QA log - {title}", "",
             f"> {DISCLAIMER}. Generated by `run.py` against the synthetic warehouse (snapshot {snapshot}).", "",
             "WARN means a real data issue was found and handled (documented, excluded, or routed for cleanup), "
             "not that a number is wrong.", "", "| Status | Check | Observed | Rule applied |", "|---|---|---|---|"]
    lines += [f"| {icon[c['status']]} | {c['check']} | {c['observed']} | {c['rule']} |" for c in qa]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


